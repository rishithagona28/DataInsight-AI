"""
Robust CSV loading.

Real-world CSVs are messy. A plain `pd.read_csv(file)` crashes or silently
mis-reads most of what Excel, banks and ERP systems export. This module reads
the raw bytes once and works out, step by step:

  1. ENCODING   UTF-8, UTF-8 with BOM, UTF-16, or Windows-1252 (Excel's plain "CSV")
  2. DELIMITER  comma, semicolon (European Excel), tab, or pipe
  3. HEADER     skips title / "Generated by ..." lines above the real header row
  4. BAD ROWS   rows with too many fields are skipped and counted, not fatal
  5. NUMBERS    "₹ 45,000", "$1,200.50", "12%" stored as text become real numbers

It returns the DataFrame plus a list of plain-language notes describing what
it detected or fixed, so the app can tell the user instead of failing silently.
"""
from __future__ import annotations

import csv
import io
import re
from collections import Counter

import pandas as pd

DELIMITERS = [",", ";", "\t", "|"]
DELIMITER_NAMES = {",": "comma", ";": "semicolon", "\t": "tab", "|": "pipe"}
SAMPLE_LINES = 60          # how many lines to inspect when guessing the format
MAX_PREAMBLE_LINES = 20    # how many title lines we're willing to skip

_CURRENCY_CHARS = re.compile(r"[₹$€£¥,\s%]|(?i:rs\.?|inr|usd)")
_NUMBERISH = re.compile(r"^\(?-?\d+(\.\d+)?\)?$")


class CSVLoadError(ValueError):
    """Raised with a user-friendly message when a file can't be read as a table."""


# --------------------------------------------------------------------------- 1. encoding
def _decode(data: bytes) -> tuple[str, str]:
    if data.startswith(b"\xef\xbb\xbf"):
        return data[3:].decode("utf-8", errors="replace"), "UTF-8 (with BOM)"
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16"), "UTF-16"
    try:
        return data.decode("utf-8"), "UTF-8"
    except UnicodeDecodeError:
        pass
    try:
        return data.decode("cp1252"), "Windows-1252"
    except UnicodeDecodeError:
        # latin-1 maps every byte to a character, so it never fails
        return data.decode("latin-1"), "Latin-1"


# --------------------------------------------------------------------------- 2 + 3. delimiter and header
def _field_count(line: str, delim: str) -> int:
    try:
        return len(next(csv.reader([line], delimiter=delim)))
    except (csv.Error, StopIteration):
        return 0


def _detect_layout(text: str) -> tuple[str, int]:
    """Pick the delimiter and header row that make the data most table-like.

    For each candidate delimiter and each possible start line, we look at how
    many fields the following lines have. Real data has a consistent field
    count (>= 2) across many lines; title rows above the header don't match it.
    """
    lines = [l for l in text.splitlines()[: SAMPLE_LINES + MAX_PREAMBLE_LINES]]
    best = (",", 0, -1.0)
    for delim in DELIMITERS:
        counts = [_field_count(l, delim) if l.strip() else 0 for l in lines]
        for start in range(min(MAX_PREAMBLE_LINES, max(len(lines) - 1, 0)) + 1):
            window = [c for c in counts[start : start + SAMPLE_LINES] if c > 0]
            if len(window) < 2:
                continue
            width, freq = Counter(window).most_common(1)[0]
            if width < 2 or counts[start] != width:
                continue
            # consistency first, then more columns, then fewer skipped lines
            score = freq / len(window) * 1000 + width - start * 0.5
            if score > best[2]:
                best = (delim, start, score)
    return best[0], best[1]


# --------------------------------------------------------------------------- 5. numbers stored as text
def _coerce_numeric_text(df: pd.DataFrame) -> list[tuple[str, str]]:
    """Convert text columns like "₹ 45,000" or "12.5%" into numbers.

    Only columns that actually contained currency symbols, thousands
    separators or % signs are converted, and only if (nearly) every value
    parses. Plain codes like PIN codes or IDs that pandas left as text are
    untouched, because they contain none of those characters.
    """
    converted = []
    for col in df.columns:
        s = df[col]
        if not (pd.api.types.is_object_dtype(s) or pd.api.types.is_string_dtype(s)):
            continue
        vals = s.dropna().astype(str).str.strip()
        vals = vals[vals != ""]
        if vals.empty or not vals.str.contains(r"[₹$€£¥,%]|(?i:rs\.?|inr|usd)", regex=True).any():
            continue
        cleaned = vals.str.replace(_CURRENCY_CHARS, "", regex=True)
        if not cleaned.str.match(_NUMBERISH).mean() >= 0.95:
            continue
        numbers = pd.to_numeric(cleaned.str.strip("()"), errors="coerce")
        negative = cleaned.str.startswith("(") & cleaned.str.endswith(")")  # accounting style: (1,200) = -1200
        numbers[negative] = -numbers[negative]
        df[col] = numbers.reindex(s.index)  # blanks stay missing (NaN)
        converted.append((col, vals.iloc[0]))  # keep one original value to show the user
    return converted


# --------------------------------------------------------------------------- main entry point
def load_csv_bytes(data: bytes) -> tuple[pd.DataFrame, list[str]]:
    """Parse raw CSV bytes into a DataFrame. Returns (df, notes)."""
    if not data or not data.strip():
        raise CSVLoadError("The file is empty.")

    notes: list[str] = []
    text, encoding = _decode(data)
    if encoding not in ("UTF-8", "UTF-8 (with BOM)"):
        notes.append(f"Read the file using **{encoding}** text encoding.")

    delim, header_row = _detect_layout(text)
    if delim != ",":
        notes.append(f"Detected **{DELIMITER_NAMES[delim]}-separated** values.")
    if header_row:
        notes.append(f"Skipped **{header_row}** title line(s) above the column headers.")

    bad_rows: list[int] = []

    def _skip_bad_line(fields: list[str]):
        bad_rows.append(len(fields))
        return None  # drop the row

    read_opts = dict(sep=delim, skiprows=header_row, skipinitialspace=True)
    try:
        try:
            # Fast path: pandas' C parser (several times faster on big files)
            df = pd.read_csv(io.StringIO(text), engine="c", **read_opts)
        except pd.errors.ParserError:
            # Some rows are malformed: re-read with the slower Python parser,
            # which lets us skip (and count) the bad rows instead of failing.
            df = pd.read_csv(io.StringIO(text), engine="python", on_bad_lines=_skip_bad_line, **read_opts)
    except pd.errors.EmptyDataError as exc:
        raise CSVLoadError("No columns found. The file doesn't look like a table.") from exc
    except Exception as exc:  # anything else: show a readable message, not a stack trace
        raise CSVLoadError(f"Couldn't read the file as a table ({type(exc).__name__}: {exc}).") from exc

    if bad_rows:
        notes.append(
            f"Skipped **{len(bad_rows)}** row(s) that had more values than there are columns "
            "(often caused by an unquoted comma inside a value)."
        )

    # Tidy up: blank column names, fully empty rows/columns
    df.columns = [str(c).strip() or f"column_{i + 1}" for i, c in enumerate(df.columns)]
    df = df.dropna(how="all").dropna(axis=1, how="all")
    unnamed = [c for c in df.columns if c.startswith("Unnamed:")]
    if unnamed and all(df[c].isna().mean() > 0.95 for c in unnamed):
        df = df.drop(columns=unnamed)

    converted = _coerce_numeric_text(df)
    if converted:
        shown = ", ".join(f"`{c}` (e.g. \"{example}\")" for c, example in converted[:5])
        more = f" and {len(converted) - 5} more" if len(converted) > 5 else ""
        notes.append(f"Converted text into numbers in {shown}{more}.")

    if df.shape[0] == 0 or df.shape[1] == 0:
        raise CSVLoadError("The file has no usable rows or columns.")
    if df.shape[1] == 1:
        notes.append("Only **one column** was found. If that's unexpected, check the file's separator.")
    return df.reset_index(drop=True), notes
